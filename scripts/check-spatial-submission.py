from playwright.sync_api import sync_playwright,expect
with sync_playwright() as pw:
 b=pw.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 p=b.new_page(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
 errors=[];p.on('pageerror',lambda e:errors.append(str(e)))
 p.goto('http://127.0.0.1:5181/?version=5&brandDemo=1&flowPreview=submission')
 expect(p.get_by_text('Assessment submission',exact=True)).to_be_visible()
 expect(p.get_by_role('heading',name='Signature & feedback')).to_be_visible()
 expect(p.get_by_role('button',name='Submit assessment',exact=True)).to_be_disabled()
 p.evaluate('()=>Promise.all(document.getAnimations().map(a=>a.finished.catch(()=>{})))')
 assert p.get_by_role('button',name='Submit assessment',exact=True).evaluate('(e)=>getComputedStyle(e).backgroundColor')=='rgb(231, 229, 238)'
 p.get_by_role('textbox',name='Feedback for Dre').fill('Agree on further practice with Alex.')
 expect(p.get_by_role('textbox',name='Feedback for Dre')).to_have_value('Agree on further practice with Alex.')
 p.get_by_role('button',name='Collect signature',exact=True).click()
 dialog=p.get_by_role('dialog',name='Collect signature',exact=True)
 expect(dialog.get_by_role('button',name='Confirm signature')).to_be_disabled()
 dialog.get_by_role('textbox',name='Or type your full name to sign').fill('Dre Michael')
 dialog.get_by_role('button',name='Confirm signature').click()
 expect(p.get_by_text('Dre’s signature collected',exact=True)).to_be_visible()
 expect(p.get_by_role('button',name='Submit assessment',exact=True)).to_be_enabled()
 p.get_by_role('button',name='View signature',exact=True).click()
 expect(p.get_by_role('dialog')).to_contain_text('Signed by Dre Michael')
 p.get_by_role('dialog').get_by_role('button',name='Close',exact=True).last.click()
 for width in [320,390,419]:
  p.set_viewport_size({'width':width,'height':844})
  p.evaluate('()=>Promise.all(document.getAnimations().map(a=>a.finished.catch(()=>{})))')
  p.screenshot(path=f'work/submission/screen-{width}.png')
  assert p.evaluate('document.documentElement.scrollWidth<=innerWidth')
 p.get_by_role('button',name='Submit assessment',exact=True).click()
 expect(p.get_by_role('dialog')).to_contain_text('Saved on this device only')
 # Copy isolated receipt into the actual participant slot to verify production normalization.
 p.get_by_role('dialog').get_by_role('button',name='Close',exact=True).click()
 saved=p.evaluate('localStorage.getItem("lp-rosa-flow-v5-v01-preview")')
 p.evaluate('(s)=>localStorage.setItem("lp-rosa-flow-v5-v01",s)',saved)
 p.goto('http://127.0.0.1:5181/?version=5&brandDemo=1')
 expect(p.get_by_text('Dre’s signature collected',exact=True)).to_be_visible()
 expect(p.get_by_role('textbox',name='Feedback for Dre')).to_have_value('Agree on further practice with Alex.')
 assert not errors,errors
 print('PASS required acknowledgement, typed signature, feedback after completion, view signature, local submission, reload persistence and mobile widths')
 p.goto('http://127.0.0.1:5181/?version=5&brandDemo=1&flowPreview=submission')
 p.get_by_role('button',name='Collect signature',exact=True).click()
 dialog=p.get_by_role('dialog',name='Collect signature',exact=True)
 p.evaluate('()=>Promise.all(document.getAnimations().map(a=>a.finished.catch(()=>{})))')
 pad=dialog.locator('svg.spatial-signature-pad').bounding_box()
 x=pad['x']+30;y=pad['y']+40
 cdp=p.context.new_cdp_session(p)
 cdp.send('Input.dispatchTouchEvent',{'type':'touchStart','touchPoints':[{'x':x,'y':y}]})
 for i in range(1,10):cdp.send('Input.dispatchTouchEvent',{'type':'touchMove','touchPoints':[{'x':x+i*12,'y':y+(i%3)*8}]})
 cdp.send('Input.dispatchTouchEvent',{'type':'touchEnd','touchPoints':[]})
 expect(dialog.get_by_role('button',name='Confirm signature')).to_be_enabled()
 dialog.get_by_role('button',name='Confirm signature').click()
 expect(p.get_by_role('button',name='Submit assessment',exact=True)).to_be_enabled()
 p.get_by_role('button',name='View signature',exact=True).click()
 expect(p.get_by_role('dialog').locator('polyline')).to_have_count(1)
 print('PASS touch-drawn signature and recorded stroke preview')
 b.close()
