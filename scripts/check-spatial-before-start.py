from playwright.sync_api import sync_playwright,expect
with sync_playwright() as pw:
 b=pw.chromium.launch(executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 p=b.new_page(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
 errors=[];p.on('pageerror',lambda e:errors.append(str(e)))
 for width in [320,390,419]:
  p.set_viewport_size({'width':width,'height':844})
  p.goto('http://127.0.0.1:5181/?version=5&brandDemo=1&flowPreview=overview')
  widget=p.locator('.spatial-before-start')
  widget.scroll_into_view_if_needed()
  expect(widget.get_by_role('heading',name='Before you start')).to_be_visible()
  expect(widget.locator('li')).to_have_count(4)
  icon=p.locator('.overview-goals .overview-goal-icon').first.evaluate('(e)=>({w:getComputedStyle(e).width,h:getComputedStyle(e).height,svg:getComputedStyle(e.querySelector("svg")).width})')
  other=widget.locator('.overview-goal-icon').first.evaluate('(e)=>({w:getComputedStyle(e).width,h:getComputedStyle(e).height,svg:getComputedStyle(e.querySelector("svg")).width})')
  assert icon==other,(icon,other)
  step=p.locator('.overview-section-copy').first.evaluate('(e)=>({size:getComputedStyle(e).fontSize,line:getComputedStyle(e).lineHeight,small:getComputedStyle(e.querySelector("small")).fontSize})')
  item=widget.locator('.overview-section-copy').first.evaluate('(e)=>({size:getComputedStyle(e).fontSize,line:getComputedStyle(e).lineHeight,small:getComputedStyle(e.querySelector("small")).fontSize})')
  assert step==item,(step,item)
  toggle=widget.get_by_role('switch',name='Preview Do Not Disturb')
  expect(toggle).not_to_be_checked();toggle.click();expect(toggle).to_be_checked()
  toast=p.locator('.spatial-android-toast')
  expect(toast).to_contain_text('Phone settings haven’t changed')
  phone=p.locator('.phone').bounding_box();box=toast.bounding_box()
  assert box['y']>=phone['y'] and box['y']+box['height']<=phone['y']+phone['height'],(box,phone)
  p.screenshot(path=f'work/before-start/overview-{width}.png')
  toggle.focus();p.keyboard.press('Space');expect(toggle).not_to_be_checked()
  expect(toast).to_contain_text('preview off')
  assert p.evaluate('document.documentElement.scrollWidth<=innerWidth')
 p.goto('http://127.0.0.1:5181/?view=design-system&section=rosa&pattern=before-start')
 expect(p.locator('.spatial-before-start')).to_be_visible()
 assert not errors,errors
 print('PASS four tips, goals icon sizes, step typography, touch/keyboard switch, truthful toast inside phone, 320/390/419, same component in library')
 b.close()
